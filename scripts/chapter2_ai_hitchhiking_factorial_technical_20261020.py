STATUS = "TECHNICAL_AI_MUTATION_PAYOFF_PERMUTATION_FACTORIAL_NOT_REGISTERED"
HORIZON = 24
FOUNDERS = (560201, 560202)
VISITORS = (560301, 560302)
ARMS = ("near", "far")
MATING = ("delayed_control", "assurance_cost")
POLICIES = (
    "Aon_Inative",
    "Aoff_Inative",
    "Aon_Ineutral",
    "Aoff_Ineutral",
    "Aon_Ineutral_scramble",
    "Aoff_Ineutral_scramble",
)
CHECKPOINTS = (0, 1, 6, 12, 24)
LOCUS_I = 1
LOCUS_A = 2


def factors(policy):
    if policy not in POLICIES:
        raise ValueError("unregistered technical factor policy")
    a_on = policy.startswith("Aon_")
    payoff_neutral = "Ineutral" in policy
    scramble = policy.endswith("_scramble")
    if scramble and not payoff_neutral:
        raise AssertionError("genotype reassignment only under I-neutral payoff")
    return a_on, payoff_neutral, scramble


def neutralize_I_for_payoff(state):
    """Only the native reproduction() ledger sees common I=.5.

    The native inherited allele state is NEVER overwritten by this
    expression clamp. This removes I's allocation, visitor-affinity and
    pollen-attraction effect simultaneously, so it is an ARTIFICIAL payoff
    model, not a direct natural floral-investment gene knockout.
    """
    alleles=state.alleles.copy()
    alleles[:,LOCUS_I,:]=.5
    return replace(state,alleles=alleles)


def permute_whole_I_diplotypes(state, rng):
    """Preserve entire I locus allele/diplotype marginals, provenance and flags."""
    if not isinstance(rng,np.random.Generator):
        raise ValueError("explicit isolated I permutation RNG required")
    n=len(state.ids)
    idx=rng.permutation(n)
    props={}
    for key in ("alleles","allele_origin","mutation_flags"):
        a=getattr(state,key).copy()
        a[:,LOCUS_I,:]=a[idx,LOCUS_I,:]
        props[key]=a
    changed=replace(state,**props)
    for locus in (0,2):
        for key in props:
            if not np.array_equal(getattr(changed,key)[:,locus,:],
                                  getattr(state,key)[:,locus,:]):
                raise AssertionError("unshuffled M/A locus was altered")
    for key in props:
        old=getattr(state,key)[:,LOCUS_I,:]
        new=getattr(changed,key)[:,LOCUS_I,:]
        # Direct equality after applying the exact documented permutation
        # is stronger than a potentially lossy sorted multiset comparison.
        if not np.array_equal(new,old[idx]):
            raise AssertionError("I whole-diplotype reallocation is not exact")
    return changed


def summarize_census(state, origin_I_mean, census):
    if not len(state.ids):
        return dict(census=census,alive=False,N=0,A_mean=None,I_mean=None,
                    I_minus_original_source=None,A_I_individual_cov=None,
                    M_A_sha256=None,
                    A_mutation_flagged_gene_copies=0,
                    I_mutation_flagged_gene_copies=0)
    traits=state.alleles.mean(axis=2)
    a=traits[:,LOCUS_A]
    i=traits[:,LOCUS_I]
    return dict(
        census=census,alive=True,N=len(state.ids),
        A_mean=float(a.mean()),I_mean=float(i.mean()),
        I_minus_original_source=float(i.mean()-origin_I_mean),
        A_I_individual_cov=float(np.mean((a-a.mean())*(i-i.mean()))),
        # Source parity across A/M processes in I-payoff-neutral native
        # versus repeatedly artificially reassigned I genetic backgrounds.
        M_A_sha256=hashlib.sha256(np.ascontiguousarray(
            state.alleles[:,(0,2),:]).tobytes()).hexdigest(),
        A_mutation_flagged_gene_copies=int(state.mutation_flags[:,2,:].sum()),
        I_mutation_flagged_gene_copies=int(state.mutation_flags[:,1,:].sum()),
    )


def technical_path(*, founder_seed, visitor_seed, visitor_arm, setting,
                   policy, periods=HORIZON):
    if (founder_seed not in FOUNDERS or visitor_seed not in VISITORS or
            visitor_arm not in ARMS or setting not in MATING or
            type(periods) is not int or not 1<=periods<=HORIZON):
        raise ValueError("outside frozen old-source technical factorial envelope")
    a_on, payoff_neutral, scramble=factors(policy)
    design, biological=load_frozen()
    cfg=original_Q1_config(biological,setting,.01,"evolving")
    if cfg.mutation_rate!=.01 or cfg.mutation_sd!=.05 or cfg.capacity!=48:
        raise AssertionError("original native Q1 genetic kernel not retained")
    env=exposure(visitor_seed,visitor_arm)
    state=founder(design,founder_seed)
    if not (len(state.ids)==48 and np.all(state.alleles[:,2,:]==.5)):
        raise AssertionError("original PR569 founder A monomorphic")
    original_I_mean=float(state.alleles[:,LOCUS_I,:].mean())
    master=int(np.random.SeedSequence([visitor_seed,design["demography"]["repeat_seed"]]).
               generate_state(1)[0])
    rngs={k:stream(master,k,0) for k in STREAM_IDS}
    i_permutation_rng=np.random.default_rng(
        np.random.SeedSequence([master,20261020,5253]))
    checkpoints={}
    trace=np.full((periods+1,10),np.nan,dtype=float)
    movements=0
    total_selfed=total_outcrossed=0
    for t in range(periods+1):
        if t in CHECKPOINTS or t==periods:
            checkpoints[str(t)]=summarize_census(state,original_I_mean,t)
        trace[t,0]=len(state.ids)
        if len(state.ids):
            z=state.alleles.mean(axis=2)
            trace[t,1:4]=z.mean(axis=0)
            trace[t,4:7]=z.var(axis=0)
            trace[t,7:]=[len(np.unique(state.alleles[:,l])) for l in range(3)]
        if t==periods:
            break
        parents=state
        if scramble:
            parents=permute_whole_I_diplotypes(state,i_permutation_rng)
            movements+=1
        payoff=neutralize_I_for_payoff(parents) if payoff_neutral else parents
        ledger=reproduce(payoff,env.visitors[t],cfg)
        state,info=advance(parents,ledger,env.seed_candidates[t],cfg,rngs,
                           year=t,mutation_traits=(True,True,a_on))
        total_selfed+=info["resident_selfed_recruits"]
        total_outcrossed+=info["resident_outcross_recruits"]
    # HARD negative-control verification against unchanged original producer.
    # The original fixed-expression mode has A=.5 as founding allele and
    # with no de-novo A mutations is biologically identical to evolving-A
    # with third-locus mutation explicitly disabled. This is verified, not
    # assumed, as the exact negative control for the 2x2.
    original_parity=None
    if not payoff_neutral and not scramble:
        source_mode="evolving" if a_on else "fixed"
        old_task=("main",setting,.01,founder_seed,visitor_seed,
                  design["demography"]["repeat_seed"],visitor_arm,source_mode)
        original_trace,original_states=original_Q1_simulate(
            design,biological,old_task,steps=periods)
        if not np.array_equal(trace,original_trace,equal_nan=True):
            raise AssertionError("Q1 source baseline trace mismatch")
        if not np.array_equal(state.alleles,original_states[f"state_{periods}"]):
            raise AssertionError("Q1 source baseline diploid genome mismatch")
        original_parity=True
    if not a_on and len(state.ids) and not np.all(state.alleles[:,2,:]==.5):
        raise AssertionError("disabled de-novo A mutation escaped 0.5 founding state")
    if payoff_neutral and not scramble and movements:
        raise AssertionError("unexpected I genotype permutation in native arm")
    return dict(
        source_founder=founder_seed,source_visitor=visitor_seed,
        visitor_arm=visitor_arm,mating_setting=setting,
        policy=policy,original_founding_A=.5,original_I=original_I_mean,
        technical_periods=periods,a_mutation_enabled=a_on,
        I_direct_payoff_enabled=not payoff_neutral,
        I_whole_diplotype_permuted_each_generation=scramble,
        I_permutation_generations=movements,
        all_original_Q1_biology_unmodified=True,
        original_Q1_exact_trace_genome_parity=original_parity,
        end=checkpoints[str(periods)],
        checkpoint=checkpoints,
        total_selfed_recruits=total_selfed,
        total_outcrossed_recruits=total_outcrossed,
    )


def run_bounded_technical():
    groups=[]
    for mating in MATING:
        for founder_seed in FOUNDERS:
            for visitor_seed in VISITORS:
                for visitor_arm in ARMS:
                    paths={p:technical_path(founder_seed=founder_seed,
                                            visitor_seed=visitor_seed,
                                            visitor_arm=visitor_arm,
                                            setting=mating,policy=p) for p in POLICIES}
                    # Same original source genome, first visit context and RNG
                    # master. Exactly matching initial traits is mandatory.
                    starts={(row["checkpoint"]["0"]["A_mean"],
                             row["checkpoint"]["0"]["I_mean"])
                            for row in paths.values()}
                    if len(starts)!=1 or any(
                            row["original_Q1_exact_trace_genome_parity"] is not True
                            for row in (paths["Aon_Inative"],paths["Aoff_Inative"])):
                        raise AssertionError("new factor arms do not share frozen source")
                    # Under neutral I payoff, locus reallocation only changes I,
                    # and MUST keep A/M genotype trajectories exactly identical.
                    for a_label in ("Aon","Aoff"):
                        native=paths[a_label+"_Ineutral"]
                        shuffled=paths[a_label+"_Ineutral_scramble"]
                        if native["end"]["N"]!=shuffled["end"]["N"]:
                            raise AssertionError("scrambling I altered A/M population census")
                        for t in CHECKPOINTS:
                            x=native["checkpoint"][str(t)]
                            y=shuffled["checkpoint"][str(t)]
                            if (x["N"]!=y["N"] or
                                    x["M_A_sha256"]!=y["M_A_sha256"]):
                                raise AssertionError(
                                    "I genotype shuffle altered A/M genotype history")
                        if native["total_selfed_recruits"]!=shuffled["total_selfed_recruits"] \
                                or native["total_outcrossed_recruits"]!=shuffled["total_outcrossed_recruits"]:
                            raise AssertionError("I-neutral shuffle changed original parentage counts")
                    groups.append(dict(
                        setting=mating,founder_seed=founder_seed,
                        visitor_seed=visitor_seed,visitor_arm=visitor_arm,
                        originals=len(paths),paths=paths))
    if len(groups)!=2*2*2*2:
        raise AssertionError("technical factorial block count not exact")
    labels={}
    for setting in MATING:
        for arm in ARMS:
            frames=[g for g in groups if g["setting"]==setting
                    and g["visitor_arm"]==arm]
            if len(frames)!=4:
                raise AssertionError("missing founder×visitor crossed blocks")
            summary={}
            for policy in POLICIES:
                rows=[f["paths"][policy] for f in frames]
                alive=[r for r in rows if r["end"]["alive"]]
                summary[policy]=dict(
                    all_start_contexts=len(frames),
                    occupied=len(alive),
                    mean_final_I_among_survivors=float(np.mean([
                        r["end"]["I_mean"] for r in alive])) if alive else None,
                    mean_delta_I_among_survivors=float(np.mean([
                        r["end"]["I_minus_original_source"] for r in alive]))
                        if alive else None,
                    mean_final_A_among_survivors=float(np.mean([
                        r["end"]["A_mean"] for r in alive])) if alive else None,
                    total_I_genotype_scrambling_steps=sum(
                        r["I_permutation_generations"] for r in rows),
                )
            labels[setting+"|"+arm]=summary
    return dict(
        status=STATUS,
        biological_operator_modified=False,
        native_Q1_founding_A_half=True,
        registered_Q1_full_1000_updates_unmodified=True,
        technical_horizon=HORIZON,
        source_founder_ids=list(FOUNDERS),
        source_visitor_history_ids=list(VISITORS),
        matched_contexts=len(groups),
        matched_paths=len(groups)*len(POLICIES),
        original_source_parity_verified=True,
        A_M_trajectories_invariant_to_I_scramble_when_I_payoff_neutral=True,
        original_zero_A_mutant_Q1_fixed_A_control_replayed=True,
        I_native_selective_payoff_involves_cost_and_pollen_attraction=True,
        I_scrambling_is_artificial_gene_reassignment_not_natural_recombination=True,
        endpoint_summary=labels,
        matched_blocks=groups,
        inference="POST_OUTCOME_TECHNICAL_FACTORS_NO_BIOLOGICAL_CONFIRMATION",
        claim_limits=[
            "Only two original Q1 founder genomes and two visitor histories; paths share initial biological sources.",
            "Twenty-four reproductive updates do not reproduce original Q1 1000-period biological endpoints.",
            "No explicit mutation birth-parent I background allele pedigree is causally followed within this factorial; the prior sidecar trace is distinct.",
            "A mutation off forbids A mutation only; M and I still inherit and mutate normally.",
            "I expression neutralized inside payoff ledger removes both allocation and pollinator attraction functions, not the inherited I genotype.",
            "Every-generation I diplotype reallocation is an artificial genetic intervention, not plant meiosis.",
            "I shuffle disrupts M-I as well as A-I association; even a positive interaction cannot attribute the effect specifically to A-I hitchhiking.",
            "Survivor-only I means are explicitly conditioned on policy-specific occupancy.",
            "No new field, island colonization, independent biological model, preregistered effect size, confidence interval or p-value is established.",
        ],
    )


def main():
    p=argparse.ArgumentParser(description=__doc__)
    p.add_argument("--technical-only",action="store_true")
    p.add_argument("--out",type=Path)
    args=p.parse_args()
    if not args.technical_only:
        p.error("new biological confirmation is not authorized; require --technical-only")
    data=run_bounded_technical()
    body=json.dumps(data,indent=2,sort_keys=True,allow_nan=False)+"\n"
    if args.out:
        args.out.parent.mkdir(parents=True,exist_ok=True)
        if args.out.exists():
            raise FileExistsError("source-bound technical output cannot be overwritten")
        args.out.write_text(body,encoding="utf8")
    else:
        print(body,end="")


if __name__=="__main__":
    main()
