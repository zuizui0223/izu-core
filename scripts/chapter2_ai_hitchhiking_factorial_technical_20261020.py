"""Bounded factorial mechanism probe for A-mutation-mediated I transmission.

This is ENGINEERING / source-compatibility exploration, NOT a preregistered
biological confirmation or an explanation of PR #569's founder sign reversals.
The native Model3 functions reproduce(), advance(), inherit(), external Q1
founder construction, mutation law and visitor histories are UNMODIFIED.

Factors:
  (1) de novo A mutations allowed versus OFF (M/I mutations still allowed);
  (2) true I expressed in the reproductive payoff versus I expression
      neutralized to .5 for the payoff ONLY, while genuine I alleles inherit;
  (3) among I-payoff-neutralized arms, an intentionally artificial
      per-generation reassignment of whole I diplotypes among parents,
      preserving the entire current I locus diploid-genotype marginal
      while breaking I associations with BOTH A and M. This is NOT natural
      recombination or an A-specific causal intervention.

Only two already exposed original Q1 founders x two already exposed visitor
histories x near/far x two mating rules x 6 policies x 24 periods are tested.
No new independent source/visitor samples, no mutation-origin birth labels,
no long-term sweep or field inference, and no new source-supported manuscript
Results are generated by this script.
"""
