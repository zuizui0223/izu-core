"""Source-stratified exploratory uncertainty for already exposed TECHNICAL scores.

This helper consumes precomputed HELDOUT source-wise prediction losses produced
by the bounded source-disjoint pilot. It does NOT fit a model, update biology,
form a prospective confidence interval, infer causal trait effects or create new
source genotypes. All 8 stochastic repeats × 4 artificial islands within one
source genotype are kept together; only the 24 distinct source genotypes
are resampled, four within each prespecified A_hint×I_hint stratum.
"""
from __future__ import annotations

from collections import defaultdict
import math
import numpy as np

BINARY_SCORE_MODELS = ("ecology_only","ecology_A","ecology_I","ecology_A_I")
DIFF_LABELS = ("A_vs_ecology", "I_vs_ecology", "A_I_vs_ecology", "A_minus_I")
STATUS = "TECHNICAL_STRATIFIED_SOURCE_BOOTSTRAP_EXPLORATORY_FIXED_FIT_NOT_CONFIRMATORY"


def source_block_bootstrap(source_rows: list[dict], *, n_boot: int=4000,
                           seed: int=80120261020) -> dict:
    if type(n_boot) is not int or n_boot < 100 or n_boot > 100000:
        raise ValueError("bootstrap replicate count must be 100..100000")
    if type(seed) is not int or seed < 0:
        raise ValueError("bootstrap seed must be a nonnegative integer")
    if len(source_rows) != 24:
        raise ValueError("source-disjoint technical design requires exactly 24 source groups")
    by_stratum = defaultdict(list)
    seen_ids, seen_seeds = set(), set()
    for record in source_rows:
        source_id = record.get("source_id")
        seed_id = record.get("source_seed")
        if (type(source_id) is not int or type(seed_id) is not int
                or source_id in seen_ids or seed_id in seen_seeds
                or type(record.get("paths")) is not int or record["paths"]!=32):
            raise ValueError("invalid or duplicated whole-source unit")
        seen_ids.add(source_id); seen_seeds.add(seed_id)
        key = (record.get("a_source_hint"),record.get("i_source_hint"))
        if key not in {(a,i) for a in (.2,.5,.8) for i in (.3,.7)}:
            raise ValueError("wrong prespecified stratification")
        losses = record.get("brier_by_model",{})
        if set(losses) != set(BINARY_SCORE_MODELS):
            raise ValueError("wrong fitted-model inventory")
        values=np.asarray([losses[k] for k in BINARY_SCORE_MODELS],dtype=float)
        if not np.isfinite(values).all() or ((values<0)|(values>1)).any():
            raise ValueError("out-of-domain Brier source losses")
        ecology,A,I,AI=map(float,values)
        by_stratum[key].append(np.array([A-ecology,I-ecology,AI-ecology,A-I],
                                        dtype=float))
    if len(by_stratum)!=6 or any(len(v)!=4 for v in by_stratum.values()):
        raise ValueError("four distinct source genotypes per each of six source strata required")

    rng=np.random.default_rng(seed)
    partial=np.zeros((n_boot,len(DIFF_LABELS)),dtype=float)
    source_values=[]
    for key in sorted(by_stratum):
        block=np.stack(by_stratum[key])
        source_values.extend(block)
        draws=rng.integers(0,4,size=(n_boot,4),endpoint=False)
        partial += block[draws].mean(axis=1)/6.
    observed=np.mean(np.stack(source_values),axis=0)
    if not np.isfinite(partial).all() or (abs(partial.mean(axis=0)) > 1).any():
        raise ValueError("invalid descriptive source-bootstrap samples")
    quantiles=np.quantile(partial,[.025,.975],axis=0)
    out={}
    for i,k in enumerate(DIFF_LABELS):
        out[k]=dict(
            observed_mean_difference=float(observed[i]),
            conditional_source_bootstrap_percentile_95=[
                float(quantiles[0,i]),float(quantiles[1,i])],
            fraction_resamples_improving_score=float(np.mean(partial[:,i]<0)),
        )
    if abs(out["A_minus_I"]["observed_mean_difference"] -
           (out["A_vs_ecology"]["observed_mean_difference"] -
            out["I_vs_ecology"]["observed_mean_difference"])) > 1e-13:
        raise ArithmeticError("within-source A versus I score identity broken")
    return dict(status=STATUS,
                bootstrap_seed=seed,
                bootstrap_draws=n_boot,
                heldout_source_groups=24,
                source_groups_per_stratum=4,
                artificial_source_strata=6,
                repeat_and_island_paths_per_source=32,
                fitted_predictors_are_unchanged=True,
                bootstrap_refits_models=False,
                iid_path_or_island_interpretation=False,
                inferential_rank="postoutcome exploratory conditional on one artificial source split",
                comparisons=out,
                exclusions=[
                    "No new biological simulation or independent genotype was generated by this helper.",
                    "Percentiles vary over the 24 artificial held-out source labels only; fitted training predictors are held fixed.",
                    "Not a confidence interval with guaranteed coverage for new natural lineages, islands or mechanism generality.",
                    "Four synthetic island conditions are the same in source training and validation.",
                    "All stochastic outcomes within each source remain together, not 768 iid samples.",
                    "A-versus-I score improvements are predictability differences, not trait-specific causal selection shares.",
                ])
